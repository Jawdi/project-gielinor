package gielinor.builder;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;

/** Merges a validated local world into a freshly built content pack. */
public final class ImportedWorldPack {
    private static final String OLD_MAP = "OriginalGeometryPrototype";
    private static final List<String> DATA_LUA = List.of("OriginalGeometry_DoorLocations.lua",
        "OriginalGeometry_LightLocations.lua", "OriginalGeometry_StairLinks.lua", "OriginalGeometry_WaterLocations.lua");
    private record Copy(Path source, Path target) { }

    /** Merges art generated by this player from a verified recipe package. */
    static void installPlayerBuild(Path world, Path recipe, Path out, Path game) throws Exception {
        world = world.toRealPath();
        out = out.toAbsolutePath().normalize();
        if (out.startsWith(world) || world.startsWith(out)) throw new IOException("Content output must be separate from the world cache");
        if (Files.exists(out.resolve("common/media/maps"))) throw new IOException("Use a fresh content staging folder");
        var manifest = WorldRecipe.validatePackage(recipe);
        var built = json(world.resolve("built-world.json"));
        if (!built.get("packageSHA256").getAsString().equals(sha(recipe.resolve("package.json")))
                || !built.get("contentDigest").getAsString().equals(manifest.get("contentDigest").getAsString()))
            throw new IOException("Built world does not match the supplied recipe package");
        requireSHA(game.resolve("projectzomboid.jar"), built.get("gameJarSHA256").getAsString());
        var payload = built.getAsJsonObject("payloadSHA256");
        WorldRecipe.verifyPayload(world, payload);
        for (String required : List.of("world-status.json", "42/mod.info", "common/media/original_geometry_tiles.tiles",
                "common/media/maps/" + OLD_MAP + "/map.info", "common/media/maps/" + OLD_MAP + "/spawnregions.lua"))
            if (!payload.has(required)) throw new IOException("World build is missing " + required);
        Path info = out.resolve("42/mod.info");
        String contentInfo = Files.readString(info);
        if (!contentInfo.lines().anyMatch(line -> line.equals("id=ProjectGielinorContent")))
            throw new IOException("Expected a fresh ProjectGielinorContent staging folder");
        var status = json(world.resolve("world-status.json"));
        if (status.get("completeCells").getAsInt() < 1 || status.get("haloDifferences").getAsInt() != 0)
            throw new IOException("World layout has no complete cell coverage");
        var copies = new ArrayList<Copy>();
        for (var entry : payload.entrySet()) {
            String name = entry.getKey();
            Path source = WorldRecipe.input(world, name);
            if (name.startsWith("common/media/")) {
                String mapped = name.replace("common/media/maps/" + OLD_MAP + "/", "common/media/maps/Gielinor/");
                copies.add(new Copy(source, insideOutput(out, mapped)));
            } else if ((name.startsWith("42/media/lua/client/") || name.startsWith("42/media/lua/server/"))
                    && DATA_LUA.contains(source.getFileName().toString())) copies.add(new Copy(source, insideOutput(out, name)));
        }
        for (String name : DATA_LUA) if (copies.stream().noneMatch(c -> c.source().getFileName().toString().equals(name)))
            throw new IOException("World layout is missing " + name);
        if (copies.stream().noneMatch(c -> c.target().endsWith("Gielinor/map.info"))) throw new IOException("World layout has no imported map");
        for (String critical : List.of("common/media/world-depth-receipt.json", "common/media/gielinor-depth/runtime.properties",
                "common/media/gielinor-depth/frames.bin", "common/media/gielinor-depth/frames.tsv"))
            if (!payload.has(critical)) throw new IOException("World build is missing " + critical);
        var properties = new java.util.Properties();
        try (var input = Files.newInputStream(world.resolve("common/media/gielinor-depth/runtime.properties"))) { properties.load(input); }
        requireSHA(world.resolve("common/media/world-depth-receipt.json"), properties.getProperty("sourceReceiptSHA256"));
        requireSHA(world.resolve("common/media/gielinor-depth/frames.bin"), properties.getProperty("framesDataSHA256"));
        requireSHA(world.resolve("common/media/gielinor-depth/frames.tsv"), properties.getProperty("framesIndexSHA256"));
        var declarations = Files.readAllLines(world.resolve("42/mod.info")).stream()
            .filter(line -> line.startsWith("pack=") || line.startsWith("tiledef=")).toList();
        if (!declarations.contains("pack=original_geometry_tiles") || declarations.stream().noneMatch(s -> s.startsWith("tiledef=original_geometry_tiles ")))
            throw new IOException("Imported tile declarations are missing");
        for (Copy copy : copies) if (Files.exists(copy.target())) throw new IOException("Content file collision: " + copy.target());
        for (Copy copy : copies) {
            Files.createDirectories(copy.target().getParent());
            String name = copy.target().getFileName().toString();
            if (!name.endsWith(".lua") && !name.endsWith(".info")) {
                try { Files.createLink(copy.target(), copy.source()); }
                catch (IOException unavailable) { Files.copy(copy.source(), copy.target()); }
            } else Files.copy(copy.source(), copy.target());
        }
        Path map = out.resolve("common/media/maps/Gielinor");
        for (Path file : List.of(map.resolve("map.info"), map.resolve("spawnregions.lua")))
            Files.writeString(file, Files.readString(file).replace(OLD_MAP, "Gielinor")
                .replace("title=Gielinor world conversion", "title=Gielinor")
                .replace("Full-cache geometry conversion in progress.", "The mainland of Gielinor."));
        Files.writeString(info, contentInfo.replaceAll("(?m)^(?:pack|tiledef)=.*\\R?", "")
            .replaceAll("(?m)^versionMin=.*$", "versionMin=42.21.0").stripTrailing() + "\n" + String.join("\n", declarations) + "\n");
        Path flag = out.resolve("42/media/lua/shared/Gielinor_ImportedWorld.lua");
        Files.createDirectories(flag.getParent());
        Files.writeString(flag, "GielinorImportedWorld = true\n");
        var receipt = new JsonObject();
        receipt.addProperty("schema", 1);
        receipt.addProperty("inputFingerprint", status.get("inputFingerprint").getAsString());
        receipt.addProperty("completeCells", status.get("completeCells").getAsInt());
        receipt.addProperty("emittedRegions", status.get("emittedRegions").getAsInt());
        receipt.addProperty("packageSHA256", built.get("packageSHA256").getAsString());
        receipt.addProperty("contentDigest", built.get("contentDigest").getAsString());
        receipt.addProperty("clientPlaytested", false);
        Files.writeString(out.resolve("imported-world.json"), receipt + "\n");
    }

    /** Developer preparation from existing local items; never installs or publishes. */
    public static void main(String[] args) throws Exception {
        if (args.length != 5) throw new IllegalArgumentException("Expected: <validated-stage> <stream-store> <item-pack> <new-output> <game-folder>");
        Path items = Path.of(args[2]).toRealPath();
        Path target = Path.of(args[3]).toAbsolutePath().normalize();
        if (Files.exists(target) || target.startsWith(items)) throw new IOException("Use a new output folder outside the item pack");
        if (!Files.readAllLines(items.resolve("42/mod.info")).contains("id=ProjectGielinorContent")
                || Files.exists(items.resolve("imported-world.json")))
            throw new IOException("Expected an existing item-only content pack");
        Files.createDirectories(target);
        try (var paths = Files.walk(items)) {
            for (Path source : paths.filter(Files::isRegularFile).toList()) {
                if (!source.toRealPath().startsWith(items)) throw new IOException("Item symlink leaves the source pack");
                String relative = items.relativize(source).toString().replace('\\', '/');
                if (relative.equals("built-by.txt") || relative.startsWith("common/media/maps/")
                        || relative.startsWith("common/media/texturepacks/gielinor_tiles")
                        || relative.equals("common/media/gielinor_tiles.tiles")) continue;
                Path to = insideOutput(target, relative);
                Files.createDirectories(to.getParent());
                Files.copy(source, to);
            }
        }
        install(Path.of(args[0]), Path.of(args[1]), target, Path.of(args[4]), true);
        Path builder = Path.of(ImportedWorldPack.class.getProtectionDomain().getCodeSource().getLocation().toURI());
        if (!Files.isRegularFile(builder)) throw new IOException("Run candidate preparation from the packaged builder jar");
        Files.writeString(target.resolve("built-by.txt"), sha(builder) + "\n", StandardCharsets.UTF_8);
        System.out.println("PREPARED combined content candidate at " + target + "; not installed, not published, client untested");
    }

    static void install(Path stage, Path stream, Path out, Path game) throws Exception {
        install(stage, stream, out, game, false);
    }
    private static void install(Path stage, Path stream, Path out, Path game, boolean linkImmutableAssets) throws Exception {
        stage = stage.toRealPath();
        stream = stream.toRealPath();
        out = out.toAbsolutePath().normalize();
        if (out.startsWith(stage) || stage.startsWith(out) || out.startsWith(stream) || stream.startsWith(out))
            throw new IOException("Build output must be separate from the validated world and stream store");
        if (Files.exists(out.resolve("common/media/maps")))
            throw new IOException("Build into a fresh staging folder; refusing to overwrite an existing map");
        JsonObject validation = json(stage.resolve("validation-receipt.json"));
        JsonObject status = json(stage.resolve("world-status.json"));
        if (!"exact-depth-streaming".equals(validation.get("clientResourceMode").getAsString())
                || status.get("completeCells").getAsInt() < 1
                || status.get("haloDifferences").getAsInt() != 0)
            throw new IOException("The world has no valid streaming/coverage receipt");
        requireSHA(game.resolve("projectzomboid.jar"), validation.get("gameJarSHA256").getAsString());
        requireSHA(stage.resolve("client-streaming-check.json"), validation.get("streamingCheckSHA256").getAsString());
        JsonObject proof = json(stage.resolve("client-streaming-check.json"));
        JsonObject store = json(stream.resolve("receipt.json"));
        requireSHA(stream.resolve("receipt.json"), proof.get("storeReceiptSHA256").getAsString());
        requireSHA(stage.resolve("common/media/world-depth-receipt.json"), store.get("sourceReceiptSHA256").getAsString());
        for (var evidence : proof.getAsJsonObject("evidenceSHA256").entrySet())
            requireSHA(inside(stage, evidence.getKey()), evidence.getValue().getAsString());

        var copies = new ArrayList<Copy>();
        for (var entry : validation.getAsJsonObject("payloadSHA256").entrySet()) {
            Path source = inside(stage, entry.getKey());
            requireSHA(source, entry.getValue().getAsString());
            String name = entry.getKey().replace('\\', '/');
            if (name.startsWith("common/media/")) {
                String mapped = name.replace("common/media/maps/" + OLD_MAP + "/", "common/media/maps/Gielinor/");
                copies.add(new Copy(source, insideOutput(out, mapped)));
            } else if ((name.startsWith("42/media/lua/client/") || name.startsWith("42/media/lua/server/"))
                    && DATA_LUA.contains(source.getFileName().toString())) {
                copies.add(new Copy(source, insideOutput(out, name)));
            }
        }
        if (copies.stream().noneMatch(c -> c.target().endsWith("Gielinor/map.info")))
            throw new IOException("Validated payload is missing the imported map");
        for (String name : DATA_LUA) if (copies.stream().noneMatch(c -> c.source().getFileName().toString().equals(name)))
            throw new IOException("Validated payload is missing " + name);
        var storeFiles = store.getAsJsonObject("files");
        if (storeFiles.size() != 3) throw new IOException("Unexpected stream-store payload");
        for (String name : List.of("frames.bin", "frames.tsv", "runtime.properties")) {
            requireSHA(inside(stream, name), storeFiles.get(name).getAsString());
            copies.add(new Copy(inside(stream, name), insideOutput(out, "common/media/gielinor-depth/" + name)));
        }
        String metadata = Files.readString(out.resolve("42/mod.info"), StandardCharsets.UTF_8)
            .replaceAll("(?m)^(?:pack|tiledef)=.*\\R?", "")
            .replaceAll("(?m)^versionMin=.*$", "versionMin=42.21.0");
        var declarations = Files.readAllLines(stage.resolve("42/mod.info")).stream()
            .filter(line -> line.startsWith("pack=") || line.startsWith("tiledef=")).toList();
        if (!declarations.contains("pack=original_geometry_tiles")
                || declarations.stream().noneMatch(line -> line.startsWith("tiledef=original_geometry_tiles ")))
            throw new IOException("Imported tile declarations are missing");
        for (Copy copy : copies) if (Files.exists(copy.target()))
            throw new IOException("Imported world collides with an existing content file: " + copy.target());
        for (Copy copy : copies) {
            Files.createDirectories(copy.target().getParent());
            String name=copy.target().getFileName().toString();
            if (linkImmutableAssets && !name.endsWith(".lua") && !name.endsWith(".info")) {
                try { Files.createLink(copy.target(), copy.source()); }
                catch (IOException unavailable) { Files.copy(copy.source(), copy.target(), StandardCopyOption.COPY_ATTRIBUTES); }
            } else Files.copy(copy.source(), copy.target(), StandardCopyOption.COPY_ATTRIBUTES);
        }
        Path map = out.resolve("common/media/maps/Gielinor");
        for (Path path : List.of(map.resolve("spawnregions.lua"), map.resolve("map.info"))) {
            String text = Files.readString(path, StandardCharsets.UTF_8).replace(OLD_MAP, "Gielinor")
                .replace("title=Gielinor world conversion", "title=Gielinor")
                .replace("Full-cache geometry conversion in progress.", "The mainland of Gielinor.");
            Files.writeString(path, text, StandardCharsets.UTF_8);
        }
        Files.writeString(out.resolve("42/mod.info"), metadata.stripTrailing() + "\n"
            + String.join("\n", declarations) + "\n", StandardCharsets.UTF_8);
        Path flag = out.resolve("42/media/lua/shared/Gielinor_ImportedWorld.lua");
        Files.createDirectories(flag.getParent());
        Files.writeString(flag, "GielinorImportedWorld = true\n", StandardCharsets.UTF_8);
        var receipt = new JsonObject();
        receipt.addProperty("schema", 1);
        receipt.addProperty("inputFingerprint", status.get("inputFingerprint").getAsString());
        receipt.addProperty("completeCells", status.get("completeCells").getAsInt());
        receipt.addProperty("emittedRegions", status.get("emittedRegions").getAsInt());
        receipt.addProperty("sourceValidationSHA256", sha(stage.resolve("validation-receipt.json")));
        receipt.addProperty("clientPlaytested", false);
        Files.writeString(out.resolve("imported-world.json"), receipt + "\n", StandardCharsets.UTF_8);
    }

    private static JsonObject json(Path path) throws IOException {
        return JsonParser.parseString(Files.readString(path, StandardCharsets.UTF_8)).getAsJsonObject();
    }
    private static Path insideOutput(Path root, String relative) throws IOException {
        Path path = root.resolve(relative).normalize();
        if (!path.startsWith(root) || Path.of(relative).isAbsolute() || relative.contains("\\"))
            throw new IOException("Unsafe imported path: " + relative);
        return path;
    }
    private static Path inside(Path root, String relative) throws IOException {
        Path path = insideOutput(root, relative).toRealPath();
        if (!path.startsWith(root)) throw new IOException("Imported symlink leaves the validated folder");
        return path;
    }
    private static void requireSHA(Path path, String expected) throws Exception {
        if (!sha(path).equals(expected)) throw new IOException("Imported content changed: " + path);
    }
    private static String sha(Path path) throws Exception {
        var digest = MessageDigest.getInstance("SHA-256");
        try (var input = Files.newInputStream(path)) {
            byte[] bytes = new byte[1024 * 1024];
            for (int n; (n = input.read(bytes)) != -1;) digest.update(bytes, 0, n);
        }
        return HexFormat.of().formatHex(digest.digest());
    }
}
